def set_paragraphs(shape, texts):
    """문단 수가 모자라면 마지막 문단을 복제해 서식을 그대로 이어 쓴다."""
    tf = shape.text_frame
    paras = [p for p in tf.paragraphs if p.runs]
    while len(paras) < len(texts):
        last = paras[-1]
        last._p.addnext(copy.deepcopy(last._p))
        paras = [p for p in tf.paragraphs if p.runs]
    for i, p in enumerate(paras):
        new = texts[i] if i < len(texts) else ''
        p.runs[0].text = new
        for r in p.runs[1:]:
            r.text = ''


def main():
    prs = Presentation(SRC)
    touched = 0
    for no, slide in enumerate(prs.slides, 1):
        shapes = list(slide.shapes)
        # 하단 식별자는 전 장 공통
        for idx, sh in enumerate(shapes):
            if not sh.has_text_frame:
                continue
            t = sh.text_frame.text.strip()
            if t.startswith('신규 시스템 개발  |') or t.startswith('도면관리 시스템(TDMS) 구축  |'):
                set_paragraphs(sh, [FOOT])
            elif re.fullmatch(r'\d{2}', t):           # 쪽번호
                set_paragraphs(sh, [f'{no:02d}'])
        for idx, texts in FILL.get(no, {}).items():
            sh = shapes[idx]
            assert sh.has_text_frame, f'slide {no} shape {idx} has no text frame'
            set_paragraphs(sh, texts)
            touched += 1
    prs.save(DST)
    print('saved', DST, '| 채운 도형', touched)


if __name__ == '__main__':
    main()
